#! /usr/bin/env python3
"""Shared helpers for the glGet size/semantics test suite.

The per-feature/per-extension glGet pname map lives in ``<suite>/glget_groups.json``
(generated by ``src/glget_groups_gen.py`` from the Khronos registry).  Each
descriptor carries the pname's ``name``/``value``/``size`` and its *getter family*
-- the call you must make to read it.  :class:`GLGetCheckMixin` turns a descriptor
into a live check:

* ``state`` / ``state?`` -- read with ``glGetIntegerv`` (or the indexed
  ``glGetIntegeri_v`` for pnames in :data:`INDEXED_STATE`) and assert the returned
  array matches the recorded size.  ``state?`` (registry-ungrouped) is probed
  tolerantly: a driver that rejects it with ``INVALID_ENUM`` skips rather than fails.

Object-scoped families (``program``, ``uniform_block``, ``atomic_counter_buffer``,
``program_interface``) need a set-up GL object, so those are exercised by curated,
spec-driven round-trips in the per-feature test modules -- this mixin just supplies
the size/dimension assertion they share.

These checks are the oracle for correcting ``src/glgetsizes.csv``: a size mismatch
here means the CSV (and the generated ``_glgets.py``) is wrong.
"""

import os
import json
import ctypes

import OpenGL
from OpenGL import error
from OpenGL.arrays.arraydatatype import ArrayDatatype

HERE = os.path.dirname(os.path.abspath(__file__))

#: GetPName pnames that MUST be read with the indexed getter (glGetIntegeri_v);
#: the registry's ``GetPName`` group does not distinguish these from plain vectors.
INDEXED_STATE = {
    'GL_MAX_COMPUTE_WORK_GROUP_COUNT',
    'GL_MAX_COMPUTE_WORK_GROUP_SIZE',
    'GL_MAX_MESH_WORK_GROUP_COUNT_EXT',
    'GL_MAX_MESH_WORK_GROUP_SIZE_EXT',
    'GL_MAX_TASK_WORK_GROUP_COUNT_EXT',
    'GL_MAX_TASK_WORK_GROUP_SIZE_EXT',
}

#: byte-array pnames whose canonical getter is glGetUnsignedBytev (not glGetFloatv);
#: drivers disagree on glGetFloatv for these, so the float sentinel probe is invalid
#: -- their sizes come from the spec (GL_UUID_SIZE_EXT=16, GL_LUID_SIZE_EXT=8).  The
#: registry can't distinguish them (both byte and int getters use group GetPName).
BYTE_ARRAY_STATE = {
    'GL_DEVICE_UUID_EXT',
    'GL_DRIVER_UUID_EXT',
    'GL_DEVICE_LUID_EXT',
}

#: enum-value ranges that crash/segfault some drivers during a blind glGet (carried
#: over from tests/test_core.py::test_glget -- transform-feedback varying buffers
#: and per-vertex atomic-counter bindings that are unsafe to read without setup).
_CRASH_GUARD = ((0x8DF9, 0x8E23), (0x92BE, 0x92C9))


def crashes(value):
    return any(lo <= value <= hi for lo, hi in _CRASH_GUARD)


_STATE_FAMILIES = ('state', 'state?')


def load_groups(suite):
    with open(os.path.join(HERE, suite, 'glget_groups.json')) as fh:
        return json.load(fh)


def feature_glgets(suite, kind, name):
    """Descriptors for one ``kind`` (``'features'``/``'extensions'``) entry."""
    return load_groups(suite)[kind][name]['glgets']


def parse_size(size_str):
    """Parse a CSV size cell to an int tuple.

    ``'(3,)#TODO ...'`` -> ``(3,)``; dynamic ``'(_L(0x86A2),)'`` -> ``None``
    (the count is only known at runtime, so callers skip the dimension assert).
    """
    expr = size_str.split('#', 1)[0].strip()
    if '_L' in expr:
        return None
    inner = expr.strip('()')
    return tuple(int(x) for x in inner.split(',') if x.strip())


def expected_count(size_str):
    """Total element count a size cell describes ((4,4) -> 16); None if dynamic."""
    size = parse_size(size_str)
    if size is None:
        return None
    n = 1
    for d in size:
        n *= d
    return n


#: probe buffer length -- must exceed any real glGet output or the driver writes
#: past the buffer (heap overflow).  Fixed outputs top out at 16 (matrices), but
#: dynamic ones (GL_COMPRESSED_TEXTURE_FORMATS, ~90 on NVIDIA) are far larger, so
#: keep generous headroom.  A true size reaching this is treated as overflow/
#: dynamic and not asserted.
_PROBE_LEN = 4096
#: funky float sentinels (stored at float32 precision so untouched slots compare
#: bit-exact); a driver writing either exact value into an output is implausible.
_SENTINELS = (20345.223938, -98765.4321)


class GLGetCheckMixin:
    """Mixed into a context TestCase (supplies ``self.gl`` etc.)."""

    glget_suite = 'gl'

    # --- low level -------------------------------------------------------
    def _drain(self):
        while self.gl.glGetError() != self.gl.GL_NO_ERROR:
            pass

    def probe_int_size(self, fill):
        """True element count for an int getter, via an int sentinel.

        ``fill(buf)`` must invoke the getter writing into the passed
        ``(c_int * N)`` buffer (e.g. ``glGetProgramiv(prog, pname, buf)``).
        Returns the count, ``None`` if the getter rejects the pname, or
        ``'overflow'`` if it fills the probe.  Mirrors :meth:`true_size` for the
        object-scoped getters (program / shader / atomic-counter-buffer) that take
        an int output array.
        """
        counts = []
        for sent in (0x6B5A1D2C, -0x2C3D4E5F):
            buf = (ctypes.c_int * _PROBE_LEN)(*([sent] * _PROBE_LEN))
            try:
                fill(buf)
            except error.GLError as err:
                self._drain()
                if err.err in (self.gl.GL_INVALID_ENUM, self.gl.GL_INVALID_OPERATION,
                               self.gl.GL_INVALID_VALUE):
                    return None
                raise
            self._drain()
            changed = [i for i in range(_PROBE_LEN) if buf[i] != sent]
            n = (max(changed) + 1) if changed else 0
            counts.append(_PROBE_LEN if n >= _PROBE_LEN else n)
        if counts[0] != counts[1]:
            return None
        return 'overflow' if counts[0] >= _PROBE_LEN else counts[0]

    def true_size(self, value):
        """Number of values the driver actually writes for ``glGetFloatv(value)``.

        Fills an oversized buffer with a funky-float sentinel and counts the slots
        the driver overwrites -- so it detects both truncation (driver writes more
        than the recorded size) and over-allocation (driver writes fewer).  The
        sentinel is rounded to float32 so untouched slots compare bit-exact.

        Returns the count, ``None`` if the getter rejects the pname (not a live
        glGetFloatv query here), or ``'overflow'`` if it fills the whole probe.
        """
        counts = []
        for raw in _SENTINELS:
            sent = ctypes.c_float(raw).value
            buf = (ctypes.c_float * _PROBE_LEN)(*([sent] * _PROBE_LEN))
            try:
                self.gl.glGetFloatv(value, buf)
            except error.GLError as err:
                self._drain()
                if err.err in (self.gl.GL_INVALID_ENUM, self.gl.GL_INVALID_OPERATION):
                    return None
                raise
            self._drain()
            changed = [i for i in range(_PROBE_LEN) if buf[i] != sent]
            n = (max(changed) + 1) if changed else 0
            counts.append(_PROBE_LEN if n >= _PROBE_LEN else n)
        # require both sentinels to agree (guards the rare coincidental write)
        if counts[0] != counts[1]:
            return None
        return 'overflow' if counts[0] >= _PROBE_LEN else counts[0]

    def assert_dims(self, name, result, size):
        """Assert a glGet result has the recorded ``size`` (or is scalar-unpacked)."""
        if size is None:                       # dynamic _L size: just ensure non-empty
            self.assertTrue(len(result) >= 0)
            return
        if size == (1,) and OpenGL.SIZE_1_ARRAY_UNPACK:
            int(result)                        # unpacked scalar must be coercible
            return
        dims = ArrayDatatype.dimensions(result)
        self.assertEqual(
            dims, size,
            '%s returned dims %r, glgetsizes.csv says %r (value=%r)'
            % (name, dims, size, result),
        )

    # --- families --------------------------------------------------------
    def check_state(self, desc, tolerant=None):
        """Read a ``state``/``state?`` pname live and assert its size.

        ``tolerant`` (default: True for the ungrouped ``state?`` family) treats an
        ``INVALID_ENUM``/``INVALID_OPERATION`` as "not a live global here" and
        skips -- but a value that *is* returned is always size-checked.  Broad
        sweeps pass ``tolerant=True``; a curated per-feature test that has set the
        state up leaves it False to make a missing value a hard failure.
        """
        name = desc['name']
        value = int(desc['value'], 16)
        size = parse_size(desc['size'])
        if tolerant is None:
            tolerant = desc['family'] == 'state?'
        if crashes(value):
            self.skipTest('%s is in the unsafe-to-blind-read range' % name)
        if name in BYTE_ARRAY_STATE:
            self.skipTest('%s is a glGetUnsignedBytev byte array (not float-probeable)'
                          % name)
        if name in INDEXED_STATE:
            return self.check_state_indexed(name, value, size)

        ts = self.true_size(value)
        if ts is None:
            if tolerant:
                self.skipTest('%s is not a live glGetFloatv query on this driver'
                              % name)
            self.fail('%s returned no value (getter rejected it)' % name)
        if ts == 'overflow':
            self.skipTest('%s writes more than the probe buffer (dynamic?)' % name)
        want = expected_count(desc['size'])
        if want is not None:
            self.assertEqual(
                ts, want,
                '%s: driver writes %d value(s), glgetsizes.csv says %s (=%d elements)'
                % (name, ts, desc['size'].split('#')[0].strip(), want),
            )
        return ts

    def check_state_indexed(self, name, value, size):
        """Read an indexed GetPName pname; ``size[0]`` = number of valid indices."""
        self.assertIsNotNone(size, '%s needs a static index count' % name)
        # the indexed getter is core in desktop GL but lives in GLES3 (not GLES2)
        get_i = getattr(self.gl, 'glGetIntegeri_v', None) or \
            self.gl3.glGetIntegeri_v
        count = size[0]
        values = []
        for i in range(count):
            buf = (ctypes.c_int * 1)()
            get_i(value, i, buf)
            values.append(buf[0])
        self._drain()
        self.assertEqual(len(values), count)
        # the count is exactly right iff index == count is out of range
        buf = (ctypes.c_int * 1)()
        try:
            get_i(value, count, buf)
        except error.GLError as err:
            self.assertEqual(
                err.err, self.gl.GL_INVALID_VALUE,
                '%s index %d gave 0x%x, expected INVALID_VALUE' % (name, count, err.err),
            )
        self._drain()
        return values

    def sweep_state(self, kind, feature):
        """Run :meth:`check_state` over every state pname of a feature/extension.

        Returns the set of pname names actually checked (skips count as covered);
        use it to assert nothing in the descriptor set was silently missed.
        """
        seen = set()
        for desc in feature_glgets(self.glget_suite, kind, feature):
            if desc['family'] not in _STATE_FAMILIES:
                continue
            seen.add(desc['name'])
            with self.subTest(pname=desc['name']):
                # a SkipTest raised here (state? rejected by the driver) is
                # recorded for the subtest and the sweep continues.
                self.check_state(desc)
        return seen

    def sweep_present(self, kind):
        """Sweep state pnames for every ``kind`` entry the driver advertises.

        Returns ``(checked, present_entries, object_scoped)`` where
        ``object_scoped`` is the set of pnames that need a set-up GL object and so
        are NOT covered here (they belong in a curated per-feature test).
        """
        data = load_groups(self.glget_suite)
        checked, entries, object_scoped = 0, 0, set()
        for name, info in sorted(data[kind].items()):
            if not self._feature_present(kind, name):
                continue
            entries += 1
            for desc in info['glgets']:
                if desc['family'] in _STATE_FAMILIES:
                    checked += 1
                    with self.subTest(**{kind[:-1]: name, 'pname': desc['name']}):
                        self.check_state(desc, tolerant=True)
                else:
                    object_scoped.add(desc['name'])
        return checked, entries, object_scoped

    def _feature_present(self, kind, name):
        if kind == 'extensions':
            return name in self.extensions()
        # features are GL_VERSION_M_m / GL_ES_VERSION_M_m -- gate on context version
        digits = [int(p) for p in name.split('_') if p.isdigit()]
        return len(digits) >= 2 and tuple(digits[-2:]) <= self._context_version()

    def _context_version(self):
        """Context (major, minor); falls back to the declared ``gl_version``.

        ``self.version()`` queries ``GL_MAJOR_VERSION``, which the GLES2 module
        doesn't export, so the live query raises for ES -- use the requested
        version there.
        """
        try:
            return self.version()
        except Exception:
            return tuple(self.gl_version)
