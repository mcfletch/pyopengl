# Accept a Python list of names (deriving count) for the char** commands, as the
# glShaderSource wrapper in GLES2_2_0.py does.  glGetUniformIndices is shared
# with OpenGL.GL.
from OpenGL.lazywrapper import lazy as _lazy
from OpenGL._bytes import as_8_bit as _as_8_bit


def _string_array(names):
    if isinstance(names, (bytes, str)):
        names = [names]
    names = [_as_8_bit(n) for n in names]
    array = (ctypes.c_char_p * len(names))(*names)
    return len(names), ctypes.cast(
        array, ctypes.POINTER(ctypes.POINTER(ctypes.c_char))
    )


@_lazy(glTransformFeedbackVaryings)
def glTransformFeedbackVaryings(baseOperation, program, varyings, bufferMode):
    """glTransformFeedbackVaryings(program, ['name', ...], bufferMode)"""
    count, array = _string_array(varyings)
    return baseOperation(program, count, array, bufferMode)


