from OpenGL.lazywrapper import lazy as _lazy
from OpenGL._string_array import as_bytes_list as _as_bytes_list


@_lazy( glGetUniformIndices )
def glGetUniformIndices( baseOperation, program, uniformCount, uniformNames=None, uniformIndices=None ):
    """Look up the index within program of each of the named uniforms

    program -- the program object to ask
    uniformCount -- the count of names, for a caller passing a prepared
        ``GLchar *const *`` array
    uniformNames -- the names: a str, a bytes, a sequence of either, or such
        a prepared array
    uniformIndices -- GLuint array of uniformCount entries to write into; one
        is allocated when it is not given

    Note: parameter "uniformCount" can be omitted, which makes the signature
        glGetUniformIndices( program, uniformNames )
    instead of:
        glGetUniformIndices( program, uniformCount, uniformNames )

    A name the program does not declare, or one its compiler removed, answers
    GL_INVALID_INDEX.

    returns the GLuint array of indices
    """
    names = _as_bytes_list( uniformCount )
    if names is not None:
        # The names stand where the count does in the C ordering, so the
        # output array -- when there is one -- stands where the names do.
        if uniformNames is not None:
            uniformIndices = uniformNames
        uniformCount, uniformNames = len( names ), names
    if uniformIndices is None:
        uniformIndices = arrays.GLuintArray.zeros( (uniformCount,) )
    baseOperation( program, uniformCount, uniformNames, uniformIndices )
    return uniformIndices
