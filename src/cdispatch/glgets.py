"""Read ``_glget_size_mapping`` and emit it as a C table.

The friendly layer sizes 285 of its output arrays by looking the pname
argument up in this mapping.  It is 2,215 entries in the desktop GL table
alone, so in C it is a static sorted array and a binary search rather than a
dictionary built at import.

The *shape* is carried, not only the element count: ``glGetFloatv`` of a matrix
pname hands the caller a 4x4 array, and flattening it to sixteen numbers would
be a visible change.
"""

import ast
import os
from dataclasses import dataclass

__all__ = ['Entry', 'read_table', 'emit_table', 'emit_tables']


@dataclass(frozen=True)
class Entry:
    """One pname's output size."""

    #: The array shape to allocate, e.g. ``(1,)`` or ``(4, 4)``.
    shape: tuple = ()
    #: When set, the size is not static: query this pname with glGetIntegerv
    #: and use the answer as the element count.
    lookup: int = 0

    @property
    def count(self):
        """Total elements, or None when it has to be looked up at run time."""
        if self.lookup:
            return None
        total = 1
        for dimension in self.shape:
            total *= dimension
        return total


def _entry_from_node(node):
    """Interpret one ``_m[pname] = (...)`` right-hand side."""
    if not isinstance(node, ast.Tuple):
        return None
    dimensions = []
    for element in node.elts:
        if isinstance(element, ast.Constant) and isinstance(element.value, int):
            dimensions.append(element.value)
            continue
        if isinstance(element, ast.Call):
            function = element.func
            name = getattr(function, 'id', None) or getattr(function, 'attr', None)
            if name in ('_L', 'LookupInt') and element.args:
                pname = element.args[0]
                if isinstance(pname, ast.Constant):
                    return Entry(lookup=int(pname.value))
        return None
    return Entry(shape=tuple(dimensions))


def read_table(path):
    """``{pname: Entry}`` from one API's ``_glgets.py``."""
    with open(path, 'r', encoding='utf-8') as handle:
        tree = ast.parse(handle.read(), filename=path)
    table = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Subscript):
            continue
        owner = getattr(target.value, 'id', None)
        if owner not in ('_m', '_glget_size_mapping'):
            continue
        key = target.slice
        if not (isinstance(key, ast.Constant) and isinstance(key.value, int)):
            continue
        entry = _entry_from_node(node.value)
        if entry is not None:
            table[key.value] = entry
    return table


def emit_table(api, table):
    """The C form: a sorted array, searched by bisection."""
    lines = [
        '/* %s output sizes, from OpenGL/raw/%s/_glgets.py.  Sorted by pname so'
        % (api, api),
        ' * that the stub can bisect it. */',
        'static const PyGLGetSize pygl_glget_%s[] = {' % (api,),
    ]
    for pname in sorted(table):
        entry = table[pname]
        shape = entry.shape
        lines.append(
            '    {0x%04X, %d, %d, 0x%04X},'
            % (
                pname,
                shape[0] if len(shape) > 0 else 0,
                shape[1] if len(shape) > 1 else 0,
                entry.lookup,
            )
        )
    lines.append('};')
    lines.append(
        'static const Py_ssize_t pygl_glget_%s_count = %d;' % (api, len(table))
    )
    return '\n'.join(lines) + '\n'


def emit_tables(package_root, apis):
    """Every API's table, plus the lookup function the stubs call."""
    parts = [
        '/* Generated by src/cdispatch -- do not edit. */',
        '#ifndef PYGL_GLGETS_H',
        '#define PYGL_GLGETS_H',
        '#include "pygl.h"',
        '',
    ]
    present = []
    for api in apis:
        path = os.path.join(package_root, 'raw', api, '_glgets.py')
        if not os.path.exists(path):
            continue
        table = read_table(path)
        if not table:
            continue
        present.append(api)
        parts.append(emit_table(api, table))
        parts.append('')
    parts.append('#endif /* PYGL_GLGETS_H */')
    return '\n'.join(parts), present
