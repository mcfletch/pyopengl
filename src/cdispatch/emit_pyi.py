"""Emit ``.pyi`` stubs from the command record.

The same record the C is generated from already says which parameter becomes
the return value, which arguments a caller must supply, and what each one is,
so the stub is derived rather than written.  That is what makes shipping stubs
worth doing: ``glGenTextures(n) -> UIntArray`` is the useful form, and it comes
out of the size and direction annotations.
"""

import importlib
import keyword
import os
from pathlib import Path

from . import ctypes_model as cm
from . import emit_c, exceptional, lazy_wrappers, model

#: The package this generator writes for: the ``OpenGL/`` beside the checkout
#: this module is in.  What :func:`emit_module` reads the ``@lazy`` wrappers
#: from unless it is handed another tree.
PACKAGE_ROOT = str(Path(__file__).resolve().parents[2] / 'OpenGL')

__all__ = [
    'emit_signature',
    'emit_module',
    'emit_submodule',
    'emit_typing_stub',
    'ARRAY_ALIASES',
    'TYPING_STUB',
]

#: What each scalar converter class looks like to a type checker.
_SCALAR_ANNOTATION = {
    'GL_U': 'int',
    'GL_I': 'int',
    'GL_I64': 'int',
    'GL_U64': 'int',
    'GL_IPTR': 'int',
    'GL_HANDLE': 'int',
    # GLboolean is int, not bool: the values the specification names for these
    # are GL_TRUE and GL_FALSE, which are IntConstant, and bool is an int
    # anyway -- so int accepts both and bool would refuse the idiomatic call.
    'GL_B': 'int',
    'GL_F': 'float',
    'GL_D': 'float',
    'GL_OPAQUE': 'Any',
}

#: Array element type -> the alias the stub uses.  One alias per machine type
#: rather than per GL type, because that is the distinction a caller makes.
ARRAY_ALIASES = {
    'f': 'FloatArray',
    'd': 'DoubleArray',
    'i': 'IntArray',
    'I': 'UIntArray',
    'h': 'ShortArray',
    'H': 'UShortArray',
    'b': 'ByteArray',
    'B': 'UByteArray',
    'q': 'Int64Array',
    'Q': 'UInt64Array',
}

#: Where a per-module stub gets the array aliases.  A stub-only module: there is
#: no such module at run time and nothing imports it, but a checker resolves it
#: like any other stub, and one copy of the aliases beats 1,300.
TYPING_STUB = 'OpenGL/_typing.pyi'

_SUBMODULE_PREAMBLE = '''"""%(title)s -- generated; regenerate with src/regenerate_c.py."""

from typing import Any%(aliases)s
'''


_TYPING_PREAMBLE = '''"""The types the generated stubs annotate arrays with.

A stub-only module: nothing imports it at run time, and the stubs beside every
generated module read it rather than each declaring these for themselves.
"""

import ctypes
import sys
from collections.abc import Sequence
from typing import Any, TypeAlias

if sys.version_info >= (3, 12):
    from collections.abc import Buffer
else:  # PEP 688 arrived in 3.12; before it there is no way to say "buffer".
    from typing_extensions import Buffer

%(aliases)s
'''


def emit_typing_stub():
    """The shared alias declarations the per-module stubs import."""
    return _TYPING_PREAMBLE % {'aliases': _alias_declarations()}


_PREAMBLE = '''"""Type stubs for %(title)s, generated by src/cdispatch.

Regenerate with:  python src/regenerate_c.py
"""

import ctypes
import sys
from collections.abc import Sequence
from typing import Any, TypeAlias%(overload)s

if sys.version_info >= (3, 12):
    from collections.abc import Buffer
else:  # PEP 688 arrived in 3.12; before it there is no way to say "buffer".
    from typing_extensions import Buffer

%(aliases)s
'''


#: The namespace exports more than the registry describes -- the array types,
#: the error classes, the sub-packages, the helper libraries.  A stub is
#: exhaustive unless it says otherwise, so without this every one of those
#: would be an error in code that is correct.
_FALLBACK = '''
def __getattr__(name: str) -> Any:
    """Anything this stub does not describe.

    The generated part covers the entry points and the enums.  What is left --
    the array types, the error classes, the sub-packages and the helper
    libraries -- is described by the modules themselves.
    """
'''


def _alias_declarations():
    lines = [
        '# What may be passed where an array is wanted.  Wide, but not Any:',
        '# `Any | X` is `Any` to a type checker, and a union containing it',
        '# checks nothing while looking as though it does.  Buffer (PEP 688)',
        '# is what admits a numpy array, which is neither a Sequence nor a',
        '# memoryview to a checker.  None is a null pointer where one is',
        '# meaningful.',
    ]
    for alias in sorted(set(ARRAY_ALIASES.values())):
        lines.append(
            '%s: TypeAlias = Sequence[Any] | Buffer | ctypes._CData | None'
            % (alias,)
        )
    lines.append(
        'AnyArray: TypeAlias = Sequence[Any] | Buffer | ctypes._CData | None'
    )
    lines.append('')
    lines.append('# What is *returned*.  Any, because the shape of the result')
    lines.append('# follows the *value* of an argument rather than its type:')
    lines.append('# glGenTextures(1) hands back a scalar and glGenTextures(3)')
    lines.append('# an array, and neither is a Sequence -- a numpy array does')
    lines.append('# not register as one.  Naming a container here makes the')
    lines.append('# ordinary call, whose result goes straight into the next')
    lines.append('# entry point as an int, an error in the caller\'s report.')
    for alias in sorted(set(ARRAY_ALIASES.values())):
        lines.append('%sResult: TypeAlias = Any' % (alias,))
    lines.append('AnyArrayResult: TypeAlias = Any')
    return '\n'.join(lines)


def _array_annotation(parameter):
    """The alias for an array parameter, or the catch-all."""
    ctype = parameter.ctype
    if ctype.pointers > 1 or ctype.base == 'void':
        return 'AnyArray'
    element = cm.element_type(ctype.base)
    return ARRAY_ALIASES.get(element.buffer_format, 'AnyArray')


def _annotation(parameter):
    if parameter.is_array or parameter.is_string_pointer:
        return _array_annotation(parameter)
    macro = parameter.macro
    return _SCALAR_ANNOTATION.get(macro, 'int')


def _return_annotation(command):
    outputs = command.output_parameters
    if outputs:
        annotations = ['%sResult' % (_array_annotation(o),) for o in outputs]
        if len(annotations) == 1:
            return annotations[0]
        return 'tuple[%s]' % (', '.join(annotations),)
    if command.returns_void:
        return 'None'
    if command.return_type.pointers:
        if command.return_type.base == 'void':
            return 'int | None'
        return 'bytes'
    macro = cm.scalar_macro(command.return_type)
    return _SCALAR_ANNOTATION.get(macro, 'int')


def parameter_name(name):
    """A name a type checker will accept.

    Registry parameter names -- and the hand-maintained libraries' header names
    -- include Python keywords, which cannot appear in a stub even though the
    entry point takes its arguments positionally.
    """
    if keyword.iskeyword(name) or not name.isidentifier():
        return '%s_' % (name,)
    return name


def emit_signature(command):
    """One ``def`` line."""
    hand = emit_c.hand_written(command)
    if hand is not None:
        arguments = ', '.join(
            '%s: Any' % (parameter_name(name),) for name in hand.arg_names
        )
        return 'def %s(%s) -> %s: ...' % (
            command.name,
            arguments,
            _return_annotation(command),
        )
    # Only a trailing run of outputs can carry a default: a parameter without
    # one cannot follow a parameter with one.
    trailing = len(command.parameters)
    while trailing and command.parameters[trailing - 1].is_output:
        trailing -= 1
    parts = []
    for index, parameter in enumerate(command.parameters):
        annotation = _annotation(parameter)
        if parameter.is_output and index >= trailing:
            parts.append(
                '%s: %s | None = None'
                % (parameter_name(parameter.name), annotation)
            )
        else:
            parts.append('%s: %s' % (parameter_name(parameter.name), annotation))
    return 'def %s(%s) -> %s: ...' % (
        command.name,
        ', '.join(parts),
        _return_annotation(command),
    )


def _safe_docstring(text):
    """Make prose safe to sit inside a triple-quoted string."""
    return text.replace('\\', '\\\\').replace('"""', "'''")


def _star_exports(reexports):
    """The names a stub's ``import *`` lines already provide.

    Every re-exported module is consulted: the private declaration modules --
    ``_types``, ``_errors``, ``_glgets`` -- and the friendly ones alike.  A
    version module re-exports the one below it, and a constant both of them
    declare (``GL_TEXTURE_COMPONENTS`` is in GL 1.0 and GL 1.1 alike) would
    otherwise be declared twice in the stub.  Importing a friendly module loads
    the platform's GL library, which generating the ``_types`` stubs does
    anyway.
    """
    provided = set()
    for reexport in reexports:
        # A private declaration module is the file it names; a friendly one
        # lives beside `OpenGL.raw`'s copy rather than in it, and is what
        # actually fills the namespace a star import reaches.
        name = reexport if reexport.rsplit('.', 1)[-1].startswith('_') else (
            reexport.replace('OpenGL.raw.', 'OpenGL.', 1)
        )
        try:
            module = importlib.import_module(name)
        except ImportError:
            # A re-export naming a module that is not there provides nothing,
            # so nothing is filtered and the constants are declared as before.
            # That the module is missing at all is a defect in its own right --
            # the friendly module beside the stub imports it too and raises on
            # import -- and is what `test_every_generated_module_imports.py`
            # is for.  Failing the whole regeneration here would only make the
            # generator the thing that reports it.
            continue
        declared = getattr(module, '__all__', None)
        provided |= (
            set(declared) if declared is not None
            else {name for name in vars(module) if not name.startswith('_')}
        )
    return provided


def emit_submodule(name, commands, constants=(), extras=(), reexports=()):
    """One friendly module's stub: what a program can import from it.

    ``OpenGL.GL.ARB.vertex_array_object`` fills its namespace from the
    declaration tables when it is imported.  Nothing reading the file can
    follow that, so an editor offers no completion in it and a checker types
    every name in it as ``Any`` -- which is what the generated modules used to
    provide by being files.  This is that, without the files.

    Signatures rather than docstrings: the API-level stub beside the package
    carries the prose, and 1,300 copies of it would be most of the wheel.
    """
    aliases = sorted(
        {_array_annotation(p) for command in commands for p in command.parameters
         if p.is_array or p.is_string_pointer}
        | {alias for command in commands
           for alias in _returned_aliases(command)}
    )
    parts = [
        _SUBMODULE_PREAMBLE
        % {
            'title': name,
            # By name rather than ``import *``: a stub re-exports what it
            # imports only when asked to, so naming them keeps the aliases out
            # of what ``from this import *`` means.
            'aliases': '\nfrom OpenGL._typing import %s' % (', '.join(aliases),)
            if aliases
            else '',
        }
    ]
    for reexport in reexports:
        # The private modules -- _types, _errors, _glgets -- are real files
        # with no friendly module above them, so the stub names them where they
        # are; everything else is re-exported from the friendly module, which
        # is the one a program imports.
        if reexport.rsplit('.', 1)[-1].startswith('_'):
            parts.append('from %s import *' % (reexport,))
        else:
            parts.append(
                'from %s import *' % (reexport.replace('OpenGL.raw.', 'OpenGL.', 1),)
            )
    if reexports:
        parts.append('')

    # A constant the star-import already brings in must not be declared again:
    # the second line says nothing the first did not, and a name defined twice
    # in one stub is an error to a checker reading it.  `GL_BYTE` and its kin
    # live in `_types` beside the GL types, and every version module that
    # mentions them re-exports that module.
    provided = _star_exports(reexports)
    for constant in sorted(set(constants) - provided):
        parts.append('%s: int' % (constant,))
    if constants:
        parts.append('')

    seen = set()
    for command in sorted(commands, key=lambda item: item.name):
        if command.name in seen:
            continue
        seen.add(command.name)
        parts.append(emit_signature(command))
    if commands:
        parts.append('')

    # What the module states in Python rather than taking from the tables: its
    # glInitXxx, the constants it aliases, the entry points it builds itself.
    # Declarations rather than names, because only the reader of the module can
    # say what each one is.
    # A hand-written alias for a name the star-import already gives -- GL 1.1
    # aliases `GL_TEXTURE_COMPONENTS`, which GL 1.0 exports -- would be that
    # name defined twice in one stub, as a duplicated constant would.
    emitted = [declaration for name, declaration in extras
               if name not in provided]
    parts.extend(emitted)
    if emitted:
        parts.append('')

    # No __all__: everything here is *defined* here, and a stub exports what it
    # defines.  Listing the names again would be a second copy of the module in
    # every module, which across 1,300 of them is most of what they weigh.
    parts.append('def __getattr__(name: str) -> Any: ...')
    parts.append('')
    return '\n'.join(parts)


def _returned_aliases(command):
    """The result aliases one command's return annotation names."""
    annotation = _return_annotation(command)
    return [
        part.strip(' []')
        for part in annotation.replace('tuple[', '').split(',')
        if part.strip(' []').endswith('Result')
    ]


def _exceptional_lines(command, wrapper, generated_doc):
    """The stub lines for an entry point ``exceptional.py`` wraps.

    The wrapper's own form comes first, so a checker resolving an ambiguous
    call picks the one the docstring gives.  Where the wrapper also passes the
    C form through, the generated line follows it as a second overload; where
    it does not, the wrapper's form is the only one, and a plain ``def`` says
    so more clearly than an overload set of one.
    """
    pythonic = 'def %s(%s) -> %s:' % (
        command.name,
        ', '.join(wrapper.parameters),
        wrapper.returns,
    )
    if not wrapper.keeps_c_form:
        return [pythonic, '    """%s"""' % (_safe_docstring(wrapper.signature),), '']
    return [
        '@overload',
        pythonic,
        '    """%s"""' % (_safe_docstring(wrapper.signature),),
        '',
        '@overload',
        emit_signature(command).replace(': ...', ':', 1),
        '    """%s"""' % (_safe_docstring(generated_doc),),
        '',
    ]


def _required_arguments(command):
    """How many arguments the generated signature demands."""
    trailing = len(command.parameters)
    while trailing and command.parameters[trailing - 1].is_output:
        trailing -= 1
    return trailing


def _lazy_lines(command, wrapper, generated_doc):
    """Stub lines for an entry point a friendly module wraps with ``lazy``.

    The wrapper's own parameter list is the call it takes, and it is all that
    is known about it: the parameters carry no annotations, and the wrapper may
    return something the entry point does not -- ``glGetActiveAttrib`` answers
    three values where the C form fills four buffers. So the short form is
    typed ``Any``, which admits the documented call without claiming to know
    more than the source says, and the generated line follows it for callers
    passing the C arguments.
    """
    required, names = wrapper
    declared = [
        '%s: Any' % (parameter_name(name),) if name in required
        else '%s: Any = ...' % (parameter_name(name),)
        for name in names
    ]
    short = 'def %s(%s) -> Any:' % (command.name, ', '.join(declared))
    prose = '    """%s"""' % (_safe_docstring(
        '%s(%s) -- the form the wrapper takes' % (command.name, ', '.join(names))),)
    if len(names) >= len(command.parameters):
        # The wrapper's own list already spans every call the C form does --
        # its trailing parameters default -- so a second overload for the C
        # form would be one a checker can never reach.
        return [short, prose, '']
    return [
        '@overload',
        short,
        prose,
        '',
        '@overload',
        emit_signature(command).replace(': ...', ':', 1),
        '    """%s"""' % (_safe_docstring(generated_doc),),
        '',
    ]


def emit_module(api, commands, constants=(), package_root=None):
    """One API's stub file.

    ``package_root`` is the ``OpenGL/`` directory being generated for, so this
    can be pointed at a tree other than the one beside the generator, as
    :func:`cdispatch.emit_handwritten.emit_api` can.
    """
    # The friendly modules' `@_lazy` wrappers, whose shorter call the registry
    # cannot know about; only the decorated function's parameter list says what
    # they take.
    discovered = lazy_wrappers.discover(package_root or PACKAGE_ROOT, api)
    wrapped = {
        command.name
        for command in commands
        if exceptional.lookup(api, command.name) is not None
        or command.name in discovered
    }
    parts = [
        _PREAMBLE
        % {
            'title': 'OpenGL.%s' % (api,),
            'aliases': _alias_declarations(),
            # Only the namespace that has wrappers needs it, and an import a
            # stub does not use is one a checker reports.
            'overload': ', overload' if wrapped else '',
        }
    ]
    if constants:
        parts.append(
            '# The enums.  They are Constant instances, which subclass int.'
        )
        for name in constants:
            parts.append('%s: int' % (name,))
        parts.append('')
    seen = set()
    for command in sorted(commands, key=lambda item: item.name):
        if command.name in seen:
            # An alias declared in two feature modules is one name.
            continue
        seen.add(command.name)
        hand = emit_c.hand_written(command)
        doc = hand.signature if hand is not None else command.signature_line()
        if command.purpose:
            doc = '%s\n\n    %s' % (doc, command.purpose)
        wrapper = exceptional.lookup(api, command.name)
        if wrapper is not None:
            parts.extend(_exceptional_lines(command, wrapper, doc))
            continue
        shorter = discovered.get(command.name)
        if shorter is not None and len(shorter[0]) < _required_arguments(command):
            parts.extend(_lazy_lines(command, shorter, doc))
            continue
        # The docstring is the body.  A def cannot carry both an ellipsis body
        # and a docstring, and the docstring is the more useful of the two --
        # it is what an editor shows without importing PyOpenGL at all.
        parts.append(emit_signature(command).replace(': ...', ':', 1))
        parts.append('    """%s"""' % (_safe_docstring(doc),))
        parts.append('')
    parts.append(_FALLBACK)
    return '\n'.join(parts)
