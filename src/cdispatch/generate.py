"""Drive the whole generation pass: registry and tree in, C and stubs out."""

import os

from . import ctypes_model as cm
from . import annotations as annotations_
from . import emit_c, emit_pyi, extract, glgets, handwritten, modules as modules_

__all__ = ['generate', 'allocate_slots', 'emit_elements_header']

GENERATED_HEADER = """/* Generated by src/cdispatch -- do not edit.
 *
 * Regenerate with:  python src/regenerate_c.py
 */
"""

#: Bumped when the shape of what the generator emits changes, so that a wheel
#: can be asked which generator built it.
GENERATOR_VERSION = '1.0'


def registry_commits(registry_root):
    """Every registry revision this was generated from.

    Two of them: the OpenGL registry and the EGL one, which Khronos publishes
    separately.  Recorded so that "which registries is this wheel built from"
    is answerable from an installed wheel rather than guessed from the date.
    """
    roots = {
        'opengl': registry_root,
        'egl': os.path.normpath(
            os.path.join(registry_root, os.pardir, os.pardir, 'eglapi')
        )
        if registry_root
        else '',
    }
    return {
        name: registry_commit(root) for name, root in roots.items() if root
    }


def registry_commit(registry_root):
    """Which registry revision this was generated from, if it is a checkout.

    Recorded so that "which registry is this wheel built from" is answerable
    from an installed wheel rather than by guessing from the date.
    """
    import subprocess

    if not registry_root or not os.path.isdir(registry_root):
        return ''
    try:
        completed = subprocess.run(
            ['git', 'rev-parse', 'HEAD'],
            cwd=registry_root,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return ''
    return completed.stdout.strip() if completed.returncode == 0 else\
        ''


def provenance(registry_root):
    """The header every generated file carries."""
    commit = registry_commit(registry_root)
    return (
        '/* Generated by src/cdispatch %s from Khronos registry %s.\n'
        ' * Do not edit; regenerate with  python src/regenerate_c.py\n */'
        % (GENERATOR_VERSION, commit or 'a source tree with no revision')
    )


def allocate_slots(commands):
    """Assign each emitted binding a stable dispatch-table index.

    Sorted by ``(api, name)`` so that a registry update moves as few slots as
    possible and the diff stays readable.
    """
    return {key: index for index, key in enumerate(sorted(commands))}


def emit_elements_header(elements):
    """The static array element descriptions the stubs name."""
    lines = [
        GENERATED_HEADER,
        '#ifndef PYGL_ELEMENTS_H',
        '#define PYGL_ELEMENTS_H',
        '#include "pygl.h"',
        '',
        '/* A void * parameter promises only an address, so any contiguous',
        ' * buffer is acceptable and no conversion is needed. */',
        '/* itemsize 0: a void * parameter has no element width, so there is',
        ' * no length for a size check to compare against. */',
        'static const PyGLElement pygl_elem_any = '
        "{'*', 0, 0, 0, 0, \"ArrayDatatype\"};",
        '',
    ]
    for index, element in enumerate(elements, start=1):
        alt = list(element.matches()[1:]) + ['', '']
        lines.append(
            "static const PyGLElement pygl_elem_%s = {'%s', %s, %s, %d, %d, \"%s\"};"
            % (
                emit_c.element_name(element.base),
                element.buffer_format,
                "'%s'" % (alt[0],) if alt[0] else '0',
                "'%s'" % (alt[1],) if alt[1] else '0',
                element.itemsize,
                index,
                element.array_class,
            )
        )
    lines.append('')
    lines.append('/* An array of pointers.  No struct code matches it on the fast path,')
    lines.append(' * so every call converts through GLvoidpArray -- which is what can')
    lines.append(' * size an allocation of them. */')
    lines.append(
        'static const PyGLElement pygl_elem_voidp = '
        '{0, 0, 0, (uint8_t)sizeof(void *), %d, "GLvoidpArray"};'
        % (len(elements) + 1,)
    )
    lines.append('')
    # The names, in the order this table indexes them.  The C resolves each
    # against the mapping OpenGL.arrays hands it and fills its own array, so
    # the index below is the C's alone and no Python file has to agree with it.
    lines.append('/* The OpenGL.arrays class each index above means, resolved by')
    lines.append(' * name at configure time.  Nothing outside this file depends')
    lines.append(' * on the order. */')
    lines.append('static const char *const pygl_array_type_names[] = {')
    for name in emit_array_type_names(elements):
        lines.append('    "%s",' % (name,))
    lines.append('};')
    lines.append('#define PYGL_ARRAY_TYPE_COUNT '
                 '((Py_ssize_t)(sizeof(pygl_array_type_names) / '
                 'sizeof(pygl_array_type_names[0])))')
    lines.append('')
    lines.append('#endif /* PYGL_ELEMENTS_H */')
    return '\n'.join(lines) + '\n'


def emit_array_type_names(elements):
    """The ``OpenGL.arrays`` class names, in ``array_index`` order."""
    return (
        ['ArrayDatatype']
        + [element.array_class for element in elements]
        + ['GLvoidpArray']
    )


def emit_registration(by_api):
    """``pygl_register_generated``, which files every stub under (api, name)."""
    lines = [GENERATED_HEADER, '#include "pygl.h"', '']
    for api in by_api:
        lines.append('extern const PyGLEntry pygl_entries_%s[];' % (api,))
    lines.append('')
    lines.append('int pygl_register_generated(PyObject *mapping)')
    lines.append('{')
    for api in by_api:
        lines.append(
            '    if (pygl_register_entries(mapping, pygl_entries_%s) < 0) {' % (api,)
        )
        lines.append('        return -1;')
        lines.append('    }')
    lines.append('    return 0;')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def emit_tables_module(slots):
    """The Python-visible half of the generated tables.

    No array-type list: the C names the class each element uses and resolves it
    against ``support.array_type_map()``, so nothing here has to agree with an
    index compiled into the extension.
    """
    lines = [
        '"""Generated by src/cdispatch -- do not edit.',
        '',
        'The dispatch slot each entry point was assigned, and the entry points',
        'a hand-written C function implements.',
        '"""',
        '',
    ]
    lines.append('#: Entry points implemented by a hand-written C function.  A')
    lines.append('#: friendly module that rebuilds one of these from scratch is')
    lines.append('#: still routed to the C implementation.')
    lines.append('HANDWRITTEN = frozenset([')
    for entry in handwritten.ENTRIES:
        lines.append('    %r,' % (entry.name,))
    lines.append('])')
    lines.append('')
    lines.append('SLOTS = {')
    for key in sorted(slots):
        lines.append('    %r: %d,' % (key, slots[key]))
    lines.append('}')
    lines.append('')
    return '\n'.join(lines)


def _write_submodule_stubs(package_root, stubs_root, commands):
    """A stub beside every friendly module, from the module table.

    ``OpenGL.GL.ARB.vertex_array_object`` calls ``_define`` and its namespace
    arrives from the declaration tables, so nothing reading the file can say
    what is in it -- an editor offers no completion there and a checker types
    every name as ``Any``.  The table knows exactly: it is what the module
    would have been.

    The friendly module is read for the names it adds itself, which is the
    ``glInitXxx`` availability check.  That is one AST parse per module and no
    part of generating the C, which reads data alone.
    """
    written = 0
    for module in modules_.read_modules(package_root, extract.APIS):
        parts = module.name.split('.')
        if len(parts) < 4 or parts[1] != 'raw':
            continue
        api = parts[2]
        # OpenGL.raw.GL.ARB.foo -> OpenGL/GL/ARB/foo, the friendly module.
        relative = os.path.join(*parts[2:])
        source = os.path.join(stubs_root, relative + '.py')
        if not os.path.exists(source):
            # A generated module with no friendly module above it: nothing for
            # a stub to describe, because nothing imports that name.
            continue
        selected = [
            commands[(api, declared.name)]
            for declared in module.commands
            if (api, declared.name) in commands
        ]
        tabulated = set(module.constants) | {c.name for c in module.commands}
        _write(
            os.path.join(stubs_root, relative + '.pyi'),
            emit_pyi.emit_submodule(
                'OpenGL.%s' % (relative.replace(os.sep, '.'),),
                selected,
                constants=sorted(module.constants),
                extras=_module_definitions(source, tabulated),
                reexports=module.reexports,
            ),
        )
        written += 1
    return written


def _module_definitions(path, tabulated):
    """What a friendly module states in Python rather than taking from a table.

    ``(name, declaration)`` for its ``glInitXxx`` availability check, the
    constants it aliases by hand (``GL_DEPTH_BUFFER = GL_DEPTH``), and any
    helper it defines.  The name travels with the declaration because only this
    reader knows it: recovering it from the text afterwards means parsing back
    out what was already in hand.

    A name the tables already describe is left to them: a module that
    customises an entry point rebinds its name, and describing that as ``Any``
    would throw away the signature the record knows.
    """
    import ast

    with open(path, 'r', encoding='utf-8') as handle:
        tree = ast.parse(handle.read(), filename=path)
    declarations = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            if node.name.startswith('_') or node.name in tabulated:
                continue
            if node.name.startswith('glInit'):
                # The extension check: it takes nothing and answers a bool,
                # which is the whole of its signature.
                declarations.append(
                    (node.name, 'def %s() -> bool: ...' % (node.name,)))
            else:
                declarations.append(
                    (node.name,
                     'def %s(*args: Any, **named: Any) -> Any: ...' % (node.name,))
                )
            continue
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if not isinstance(target, ast.Name) or target.id.startswith('_'):
                continue
            if target.id in tabulated:
                continue
            declarations.append(
                (target.id,
                 '%s: %s' % (target.id,
                             'int' if _is_enum_name(target.id) else 'Any'))
            )
    return tuple(declarations)


#: The prefixes an enum name carries in every API PyOpenGL binds.  A constant
#: is an int; anything else a module binds could be any object at all.
_ENUM_PREFIXES = ('GL_', 'EGL_', 'WGL_', 'GLX_')


def _is_enum_name(name):
    return name.startswith(_ENUM_PREFIXES)


def _write(path, text):
    existing = None
    if os.path.exists(path):
        with open(path, 'r', encoding='utf-8') as handle:
            existing = handle.read()
    if existing == text:
        return False
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(text)
    return True


def generate(package_root, output_root, report=None, tables_path=None,
             stubs_root=None):
    """Generate every C artifact from the declarations, registry and table.

    The friendly modules are **not** read.  What they state is in
    ``annotations.json``, and a customisation chain still in the tree is a
    second copy of that -- so reading it would add nothing and would make the
    generated C depend on text that migrating a module deletes.  The two copies
    are compared by ``tests/cdispatch/test_annotation_wrapping.py`` for as long
    as any chain remains.

    Returns the command records, so that callers can report on coverage without
    extracting a second time.
    """
    commands = extract.extract_tree(package_root, read_chains=False)
    emittable = {
        key: command
        for key, command in commands.items()
        if emit_c.is_emittable(command)
    }
    slots = allocate_slots(emittable)
    elements = cm.known_element_types()

    os.makedirs(output_root, exist_ok=True)
    _write(
        os.path.join(output_root, 'pygl_elements.h'), emit_elements_header(elements)
    )
    glget_text, glget_apis = glgets.emit_tables(package_root, extract.APIS)
    _write(os.path.join(output_root, 'pygl_glgets.h'), glget_text)

    # The annotations, written back as data.  Nothing reads them yet -- the
    # generator still recovers them by parsing the friendly modules -- but the
    # table is checked against that parse on every run, so the day it becomes
    # the source it will already be right.
    annotation_table = annotations_.dump(commands)
    annotations_.store(annotation_table)

    raw_modules = modules_.read_modules(package_root, extract.APIS)
    # The same facts as the C table, for a build with no compiled extension --
    # and the annotations, which the pure-Python path needs to rebuild what a
    # customisation chain used to do.
    declarations = modules_.write_declarations(
        package_root, raw_modules, annotations=annotation_table
    )
    _write(
        os.path.join(output_root, 'pygl_modules.c'),
        modules_.emit_modules(raw_modules),
    )

    stamp = provenance(
        os.path.join(
            os.path.dirname(os.path.abspath(package_root)), 'src', 'khronosapi'
        )
    )
    by_api = []
    for api in extract.APIS:
        selected = [
            command
            for key, command in sorted(emittable.items())
            if key[0] == api
        ]
        if not selected:
            continue
        by_api.append(api)
        _write(
            os.path.join(output_root, 'pygl_%s.c' % (api,)),
            emit_c.emit_translation_unit(api, selected, slots, provenance=stamp),
        )
    _write(os.path.join(output_root, 'pygl_generated.c'), emit_registration(by_api))

    if stubs_root is not None:
        # One stub file per API namespace, beside the package it describes.
        constants = extract.extract_constants(package_root)
        for api in extract.APIS:
            selected = [
                command
                for key, command in sorted(commands.items())
                if key[0] == api
            ]
            if not selected:
                continue
            directory = os.path.join(stubs_root, api)
            if not os.path.isdir(directory):
                continue
            _write(
                os.path.join(directory, '__init__.pyi'),
                emit_pyi.emit_module(api, selected, constants.get(api, ())),
            )
        _write(
            os.path.join(stubs_root, '_typing.pyi'), emit_pyi.emit_typing_stub()
        )
        stub_count = _write_submodule_stubs(package_root, stubs_root, commands)
        if report is not None:
            report['module_stubs'] = stub_count
    if tables_path is not None:
        _write(tables_path, emit_tables_module(slots))

    if report is not None:
        report.update(
            {
                'generator_version': GENERATOR_VERSION,
                'registry_commits': registry_commits(
                    os.path.join(
                        os.path.dirname(os.path.abspath(package_root)),
                        'src',
                        'khronosapi',
                        'xml',
                    )
                ),
                'registry_commit': registry_commit(
                    os.path.join(
                        os.path.dirname(os.path.abspath(package_root)),
                        'src',
                        'khronosapi',
                    )
                ),
                'total': len(commands),
                'emitted': len(emittable),
                'apis': by_api,
                'glget_tables': glget_apis,
                'generated_modules': len(raw_modules),
                'declaration_bytes': declarations,
                'array_types': emit_array_type_names(elements),
            }
        )
    return commands, emittable, slots
