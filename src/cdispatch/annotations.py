"""The annotations as data: what the registry does not say about a command.

The Khronos registry gives every entry point's C signature.  What it does not
give is the difference between that and the Python one -- which argument is an
output the caller never passes, how long an array has to be, which pointer the
GL keeps reading after the call returns.  Those were written by people as
chains of ``wrapper.wrapper(...).setOutput(...)`` in the friendly modules, and
until now the generator recovered them by parsing that Python.

Parsing generated Python to recover facts is the wrong direction: every
``OpenGL/raw`` module says *"Autogenerated by xml_generate script, do not
edit"* at the top, so the generator was reading its own output.  Of 4,839
commands, 3,660 are plain pass-throughs whose every fact is in the registry;
only about 1,200 carry anything at all, and of those the registry itself
supplies or corrects 136.

So the annotations are extracted once and thereafter kept as data, and the
generator reads a registry and a table -- no Python.

The table is keyed ``"<API>.<command>"`` and parameters are keyed by **name**,
not by position: a position moves when the registry adds an argument, and a
name is what a reader recognises.
"""

import json
import os

from . import model

__all__ = ['dump', 'apply', 'load', 'store', 'without_annotations', 'PATH']

#: The checked-in table, beside this module.
PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'annotations.json')


# ------------------------------------------------------------------ writing


def _size_to_data(size):
    """One size spec as the data that describes it."""
    if size is model.NO_SIZE:
        return None
    if isinstance(size, model.Fixed):
        return {'kind': 'fixed', 'count': size.count}
    if isinstance(size, model.FromArg):
        return {'kind': 'from-argument', 'argument': size.argument,
                'divisor': size.divisor}
    if isinstance(size, model.GLGetTable):
        return {'kind': 'glget-table', 'pname': size.pname_argument}
    if isinstance(size, model.ImageSize):
        return {'kind': 'image', 'format': size.format_argument,
                'type': size.type_argument, 'dimensions': list(size.dimensions)}
    if isinstance(size, model.TypedArray):
        return {'kind': 'typed-array', 'type': size.type_argument}
    if isinstance(size, model.StringArray):
        return {'kind': 'string-array'}
    if isinstance(size, model.Computed):
        return {'kind': 'computed', 'helper': size.helper}
    raise TypeError('no data form for %r' % (size,))


def dump(commands):
    """Every command that carries an annotation, as plain data.

    Indices in the size specs become argument *names* on the way out, so that
    the table reads as a description of the call rather than of a tuple.
    """
    table = {}
    for (api, name), command in commands.items():
        names = [p.name for p in command.parameters]
        entry = {}
        if command.helper:
            entry['helper'] = command.helper
        parameters = {}
        for parameter in command.parameters:
            bits = {}
            if parameter.direction == model.OUT:
                bits['out'] = True
            size = _size_to_data(parameter.size)
            if size is not None:
                parameters_named(size, names)
                bits['size'] = size
            if parameter.retain:
                bits['retain'] = True
            if parameter.output_order:
                bits['output_order'] = parameter.output_order
            if bits:
                parameters[parameter.name] = bits
        if parameters:
            entry['parameters'] = parameters
        if entry:
            table['%s.%s' % (api, name)] = entry
    return table


def parameters_named(size, names):
    """Turn the argument indices in a size spec into argument names."""

    def name_of(index):
        return names[index] if 0 <= index < len(names) else index

    kind = size['kind']
    if kind == 'from-argument':
        size['argument'] = name_of(size['argument'])
    elif kind == 'glget-table':
        size['pname'] = name_of(size['pname'])
    elif kind == 'typed-array':
        size['type'] = name_of(size['type'])
    elif kind == 'image':
        size['format'] = name_of(size['format'])
        size['type'] = name_of(size['type'])
        size['dimensions'] = [name_of(index) for index in size['dimensions']]


# ------------------------------------------------------------------ reading


def _size_from_data(data, names):
    """The size spec a table entry describes."""

    def index_of(name):
        return names.index(name) if name in names else name

    kind = data['kind']
    if kind == 'fixed':
        return model.Fixed(data['count'])
    if kind == 'from-argument':
        return model.FromArg(index_of(data['argument']), data['divisor'])
    if kind == 'glget-table':
        return model.GLGetTable(index_of(data['pname']))
    if kind == 'image':
        return model.ImageSize(
            index_of(data['format']),
            index_of(data['type']),
            tuple(index_of(name) for name in data['dimensions']),
        )
    if kind == 'typed-array':
        return model.TypedArray(index_of(data['type']))
    if kind == 'string-array':
        return model.StringArray()
    if kind == 'computed':
        return model.Computed(data['helper'])
    raise ValueError('unknown size kind %r' % (kind,))


def apply(commands, table):
    """Annotate ``commands`` -- read from the registry -- from ``table``.

    A command the table does not mention is a pass-through and is left alone.
    A name the command does not have is ignored rather than raising: the
    registry moves, and a table entry for an argument that no longer exists
    should be reported by the coverage tool, not crash the build.
    """
    for key, entry in table.items():
        api, name = key.split('.', 1)
        command = commands.get((api, name))
        if command is None:
            continue
        if 'helper' in entry:
            command.helper = entry['helper']
        names = [p.name for p in command.parameters]
        by_name = {p.name: p for p in command.parameters}
        for parameter_name, bits in entry.get('parameters', {}).items():
            parameter = by_name.get(parameter_name)
            if parameter is None:
                continue
            if bits.get('out'):
                parameter.direction = model.OUT
            if 'size' in bits:
                parameter.size = _size_from_data(bits['size'], names)
            if bits.get('retain'):
                parameter.retain = True
            if 'output_order' in bits:
                parameter.output_order = bits['output_order']
    return commands


def without_annotations(commands):
    """A copy of ``commands`` carrying only what the registry would give.

    What the round-trip test starts from: the signatures, with every
    annotation removed, so that applying the table has to put all of them back.
    """
    import copy

    stripped = {}
    for key, command in commands.items():
        clone = copy.deepcopy(command)
        clone.helper = ''
        for parameter in clone.parameters:
            parameter.direction = model.IN
            parameter.size = model.NO_SIZE
            parameter.retain = False
            parameter.output_order = 0
        stripped[key] = clone
    return stripped


# ------------------------------------------------------------------ the file


def load(path=PATH):
    """The checked-in table."""
    with open(path, 'r', encoding='utf-8') as handle:
        return json.load(handle)


def store(table, path=PATH):
    """Write the table, sorted, so that a diff shows what a change did."""
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(table, handle, indent=1, sort_keys=True)
        handle.write('\n')
